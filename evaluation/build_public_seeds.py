def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root",type=Path,default=Path(__file__).resolve().parents[1])
    parser.add_argument("--structure-only",action="store_true")
    args=parser.parse_args(argv);root=args.root.resolve()
    if args.structure_only:
        dataset=json.loads((root/"evaluation/datasets/public_materials_hts_dev_v3.json").read_text(encoding="utf-8"))
        print(json.dumps({"structure_pages":build_structure(root,dataset),"human_approved":0}))
        return 0
    dataset=build(root)
    dialogues=build_dialogues(dataset)
    path=root/"evaluation/datasets/public_dialogues_dev_v3.json"
    if path.exists():
        raise ValueError("public dialogues already exist")
    path.write_text(json.dumps(dialogues,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    load_golden_set(path,project_root=root,verify_files=True)
    print(json.dumps({"new_local_drafts":len(dataset["items"]),"new_four_turn_groups":len(dialogues["items"]),"human_approved":0}))
    return 0


